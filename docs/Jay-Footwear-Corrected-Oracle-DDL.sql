-- Jay Footwear Sales and Inventory Management System
-- Corrected Oracle 12c+ physical model: 19 tables, 20 foreign-key columns
-- The running Node.js prototype uses equivalent SQLite data types.

CREATE TABLE ROLE (
    RoleID          NUMBER(4) GENERATED BY DEFAULT AS IDENTITY,
    RoleName        VARCHAR2(30) NOT NULL,
    RoleDescription VARCHAR2(120),
    CONSTRAINT ROLE_PK PRIMARY KEY (RoleID),
    CONSTRAINT ROLE_UK_NAME UNIQUE (RoleName)
);

CREATE TABLE CUSTOMER (
    CustomerID   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    FirstName    VARCHAR2(50) NOT NULL,
    LastName     VARCHAR2(50) NOT NULL,
    PhoneNumber  VARCHAR2(20),
    EmailAddress VARCHAR2(80) NOT NULL,
    CONSTRAINT CUSTOMER_PK PRIMARY KEY (CustomerID),
    CONSTRAINT CUSTOMER_UK_EMAIL UNIQUE (EmailAddress)
);

CREATE TABLE SUPPLIER (
    SupplierID     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    SupplierName   VARCHAR2(80) NOT NULL,
    ContactPerson  VARCHAR2(80),
    PhoneNumber    VARCHAR2(20),
    EmailAddress   VARCHAR2(80),
    SupplierStatus VARCHAR2(15) DEFAULT 'Active' NOT NULL,
    CONSTRAINT SUPPLIER_PK PRIMARY KEY (SupplierID),
    CONSTRAINT SUPPLIER_UK_NAME UNIQUE (SupplierName),
    CONSTRAINT SUPPLIER_CK_STATUS CHECK (SupplierStatus IN ('Active','Inactive'))
);

CREATE TABLE CATEGORY (
    CategoryID   NUMBER(6) GENERATED BY DEFAULT AS IDENTITY,
    CategoryName VARCHAR2(50) NOT NULL,
    Description  VARCHAR2(150),
    CONSTRAINT CATEGORY_PK PRIMARY KEY (CategoryID),
    CONSTRAINT CATEGORY_UK_NAME UNIQUE (CategoryName)
);

CREATE TABLE BRAND (
    BrandID         NUMBER(6) GENERATED BY DEFAULT AS IDENTITY,
    BrandName       VARCHAR2(50) NOT NULL,
    CountryOfOrigin VARCHAR2(50),
    CONSTRAINT BRAND_PK PRIMARY KEY (BrandID),
    CONSTRAINT BRAND_UK_NAME UNIQUE (BrandName)
);

CREATE TABLE PRODUCT_CONDITION (
    ConditionID   NUMBER(4) GENERATED BY DEFAULT AS IDENTITY,
    ConditionName VARCHAR2(30) NOT NULL,
    CONSTRAINT PRODUCT_CONDITION_PK PRIMARY KEY (ConditionID),
    CONSTRAINT PRODUCT_CONDITION_UK UNIQUE (ConditionName)
);

CREATE TABLE SHOE_SIZE (
    SizeID     NUMBER(6) GENERATED BY DEFAULT AS IDENTITY,
    SizeSystem VARCHAR2(10) NOT NULL,
    SizeValue  NUMBER(4,1) NOT NULL,
    CONSTRAINT SHOE_SIZE_PK PRIMARY KEY (SizeID),
    CONSTRAINT SHOE_SIZE_UK UNIQUE (SizeSystem, SizeValue),
    CONSTRAINT SHOE_SIZE_CK_VALUE CHECK (SizeValue > 0)
);

CREATE TABLE PAYMENT_METHOD (
    MethodID   NUMBER(4) GENERATED BY DEFAULT AS IDENTITY,
    MethodName VARCHAR2(30) NOT NULL,
    IsActive   NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PAYMENT_METHOD_PK PRIMARY KEY (MethodID),
    CONSTRAINT PAYMENT_METHOD_UK UNIQUE (MethodName),
    CONSTRAINT PAYMENT_METHOD_CK_ACTIVE CHECK (IsActive IN (0,1))
);

CREATE TABLE CUSTOMER_ADDRESS (
    AddressID   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    CustomerID  NUMBER(10) NOT NULL,
    AddressType VARCHAR2(20),
    HouseStreet VARCHAR2(100),
    Barangay    VARCHAR2(60),
    City        VARCHAR2(60) NOT NULL,
    Province    VARCHAR2(60) NOT NULL,
    PostalCode  VARCHAR2(10),
    CONSTRAINT CUSTOMER_ADDRESS_PK PRIMARY KEY (AddressID),
    CONSTRAINT CUSTOMER_ADDRESS_FK_CUST FOREIGN KEY (CustomerID)
        REFERENCES CUSTOMER (CustomerID) ON DELETE CASCADE
);

CREATE TABLE SUPPLIER_ADDRESS (
    AddressID   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    SupplierID  NUMBER(10) NOT NULL,
    HouseStreet VARCHAR2(100),
    Barangay    VARCHAR2(60),
    City        VARCHAR2(60),
    Province    VARCHAR2(60),
    PostalCode  VARCHAR2(10),
    CONSTRAINT SUPPLIER_ADDRESS_PK PRIMARY KEY (AddressID),
    CONSTRAINT SUPPLIER_ADDRESS_FK_SUPP FOREIGN KEY (SupplierID)
        REFERENCES SUPPLIER (SupplierID) ON DELETE CASCADE
);

CREATE TABLE USER_ACCOUNT (
    UserID        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    Username      VARCHAR2(50) NOT NULL,
    PasswordHash  VARCHAR2(255),
    CustomerID    NUMBER(10),
    FirstName     VARCHAR2(50) NOT NULL,
    LastName      VARCHAR2(50) NOT NULL,
    RoleID        NUMBER(4) NOT NULL,
    GoogleID      VARCHAR2(255),
    AccountStatus VARCHAR2(15) DEFAULT 'Active' NOT NULL,
    CreatedAt     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT USER_ACCOUNT_PK PRIMARY KEY (UserID),
    CONSTRAINT USER_ACCOUNT_UK_USERNAME UNIQUE (Username),
    CONSTRAINT USER_ACCOUNT_UK_GOOGLE UNIQUE (GoogleID),
    CONSTRAINT USER_ACCOUNT_CK_STATUS CHECK (AccountStatus IN ('Active','Inactive')),
    CONSTRAINT USER_ACCOUNT_FK_CUSTOMER FOREIGN KEY (CustomerID)
        REFERENCES CUSTOMER (CustomerID) ON DELETE SET NULL,
    CONSTRAINT USER_ACCOUNT_FK_ROLE FOREIGN KEY (RoleID)
        REFERENCES ROLE (RoleID)
);

CREATE TABLE PRODUCT (
    ProductID    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ProductName  VARCHAR2(100) NOT NULL,
    CategoryID   NUMBER(6) NOT NULL,
    BrandID      NUMBER(6) NOT NULL,
    ConditionID  NUMBER(4) NOT NULL,
    SellingPrice NUMBER(10,2) NOT NULL,
    ImagePath    VARCHAR2(255),
    IsActive     NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PRODUCT_PK PRIMARY KEY (ProductID),
    CONSTRAINT PRODUCT_UK_NAME_BRAND UNIQUE (ProductName, BrandID),
    CONSTRAINT PRODUCT_CK_PRICE CHECK (SellingPrice >= 0),
    CONSTRAINT PRODUCT_CK_ACTIVE CHECK (IsActive IN (0,1)),
    CONSTRAINT PRODUCT_FK_CATEGORY FOREIGN KEY (CategoryID)
        REFERENCES CATEGORY (CategoryID),
    CONSTRAINT PRODUCT_FK_BRAND FOREIGN KEY (BrandID)
        REFERENCES BRAND (BrandID),
    CONSTRAINT PRODUCT_FK_CONDITION FOREIGN KEY (ConditionID)
        REFERENCES PRODUCT_CONDITION (ConditionID)
);

CREATE TABLE PRODUCT_VARIANT (
    VariantID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ProductID NUMBER(10) NOT NULL,
    SizeID    NUMBER(6) NOT NULL,
    SKU       VARCHAR2(30) NOT NULL,
    CONSTRAINT PRODUCT_VARIANT_PK PRIMARY KEY (VariantID),
    CONSTRAINT PRODUCT_VARIANT_UK_SKU UNIQUE (SKU),
    CONSTRAINT PRODUCT_VARIANT_UK_SIZE UNIQUE (ProductID, SizeID),
    CONSTRAINT PRODUCT_VARIANT_FK_PRODUCT FOREIGN KEY (ProductID)
        REFERENCES PRODUCT (ProductID) ON DELETE CASCADE,
    CONSTRAINT PRODUCT_VARIANT_FK_SIZE FOREIGN KEY (SizeID)
        REFERENCES SHOE_SIZE (SizeID)
);

CREATE TABLE INVENTORY (
    VariantID    NUMBER(10),
    StockQuantity NUMBER(8) DEFAULT 0 NOT NULL,
    ReorderLevel  NUMBER(8) DEFAULT 1 NOT NULL,
    LastUpdated   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT INVENTORY_PK PRIMARY KEY (VariantID),
    CONSTRAINT INVENTORY_CK_STOCK CHECK (StockQuantity >= 0),
    CONSTRAINT INVENTORY_CK_REORDER CHECK (ReorderLevel >= 0),
    CONSTRAINT INVENTORY_FK_VARIANT FOREIGN KEY (VariantID)
        REFERENCES PRODUCT_VARIANT (VariantID) ON DELETE CASCADE
);

CREATE TABLE SALES_TRANSACTION (
    SaleID        NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
    SaleDate      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UserID        NUMBER(10) NOT NULL,
    CustomerID    NUMBER(10),
    OrderDiscount NUMBER(10,2) DEFAULT 0 NOT NULL,
    SaleStatus    VARCHAR2(15) NOT NULL,
    CONSTRAINT SALES_TRANSACTION_PK PRIMARY KEY (SaleID),
    CONSTRAINT SALES_TRANSACTION_CK_DISC CHECK (OrderDiscount >= 0),
    CONSTRAINT SALES_TRANSACTION_CK_STAT CHECK (SaleStatus IN ('Processing','Completed','Shipped','Cancelled')),
    CONSTRAINT SALES_TRANSACTION_FK_USER FOREIGN KEY (UserID)
        REFERENCES USER_ACCOUNT (UserID),
    CONSTRAINT SALES_TRANSACTION_FK_CUST FOREIGN KEY (CustomerID)
        REFERENCES CUSTOMER (CustomerID) ON DELETE SET NULL
);

CREATE TABLE SALES_ITEM (
    SaleItemID  NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
    SaleID      NUMBER(12) NOT NULL,
    VariantID   NUMBER(10) NOT NULL,
    Quantity    NUMBER(8) NOT NULL,
    UnitPrice   NUMBER(10,2) NOT NULL,
    LineDiscount NUMBER(10,2) DEFAULT 0 NOT NULL,
    CONSTRAINT SALES_ITEM_PK PRIMARY KEY (SaleItemID),
    CONSTRAINT SALES_ITEM_UK UNIQUE (SaleID, VariantID),
    CONSTRAINT SALES_ITEM_CK_QTY CHECK (Quantity > 0),
    CONSTRAINT SALES_ITEM_CK_PRICE CHECK (UnitPrice >= 0),
    CONSTRAINT SALES_ITEM_CK_DISC CHECK (LineDiscount >= 0),
    CONSTRAINT SALES_ITEM_FK_SALE FOREIGN KEY (SaleID)
        REFERENCES SALES_TRANSACTION (SaleID) ON DELETE CASCADE,
    CONSTRAINT SALES_ITEM_FK_VARIANT FOREIGN KEY (VariantID)
        REFERENCES PRODUCT_VARIANT (VariantID)
);

CREATE TABLE PAYMENT (
    PaymentID      NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
    SaleID         NUMBER(12) NOT NULL,
    MethodID       NUMBER(4) NOT NULL,
    PaymentDate    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    AmountPaid     NUMBER(10,2) NOT NULL,
    ReferenceNumber VARCHAR2(50),
    PaymentStatus  VARCHAR2(15) NOT NULL,
    CONSTRAINT PAYMENT_PK PRIMARY KEY (PaymentID),
    CONSTRAINT PAYMENT_CK_AMOUNT CHECK (AmountPaid >= 0),
    CONSTRAINT PAYMENT_CK_STATUS CHECK (PaymentStatus IN ('Pending','Paid','Failed','Refunded')),
    CONSTRAINT PAYMENT_FK_SALE FOREIGN KEY (SaleID)
        REFERENCES SALES_TRANSACTION (SaleID),
    CONSTRAINT PAYMENT_FK_METHOD FOREIGN KEY (MethodID)
        REFERENCES PAYMENT_METHOD (MethodID)
);

CREATE TABLE PURCHASE_ORDER (
    PurchaseOrderID NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
    SupplierID      NUMBER(10) NOT NULL,
    UserID          NUMBER(10) NOT NULL,
    OrderDate       DATE DEFAULT SYSDATE NOT NULL,
    ExpectedDate    DATE,
    ReceivedDate    DATE,
    POStatus        VARCHAR2(15) NOT NULL,
    CONSTRAINT PURCHASE_ORDER_PK PRIMARY KEY (PurchaseOrderID),
    CONSTRAINT PURCHASE_ORDER_CK_STATUS CHECK (POStatus IN ('Draft','Ordered','Partial','Received','Cancelled')),
    CONSTRAINT PURCHASE_ORDER_FK_SUPPLIER FOREIGN KEY (SupplierID)
        REFERENCES SUPPLIER (SupplierID),
    CONSTRAINT PURCHASE_ORDER_FK_USER FOREIGN KEY (UserID)
        REFERENCES USER_ACCOUNT (UserID)
);

CREATE TABLE PURCHASE_ORDER_ITEM (
    PurchaseOrderItemID NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
    PurchaseOrderID     NUMBER(12) NOT NULL,
    VariantID           NUMBER(10) NOT NULL,
    QuantityOrdered     NUMBER(8) NOT NULL,
    QuantityReceived    NUMBER(8) DEFAULT 0 NOT NULL,
    UnitCost            NUMBER(10,2) NOT NULL,
    CONSTRAINT PURCHASE_ORDER_ITEM_PK PRIMARY KEY (PurchaseOrderItemID),
    CONSTRAINT PURCHASE_ORDER_ITEM_UK UNIQUE (PurchaseOrderID, VariantID),
    CONSTRAINT PURCHASE_ORDER_ITEM_CK_QTY CHECK (QuantityOrdered > 0),
    CONSTRAINT PURCHASE_ORDER_ITEM_CK_REC CHECK (QuantityReceived >= 0 AND QuantityReceived <= QuantityOrdered),
    CONSTRAINT PURCHASE_ORDER_ITEM_CK_COST CHECK (UnitCost >= 0),
    CONSTRAINT PURCHASE_ORDER_ITEM_FK_PO FOREIGN KEY (PurchaseOrderID)
        REFERENCES PURCHASE_ORDER (PurchaseOrderID) ON DELETE CASCADE,
    CONSTRAINT PURCHASE_ORDER_ITEM_FK_VAR FOREIGN KEY (VariantID)
        REFERENCES PRODUCT_VARIANT (VariantID)
);

-- Supporting indexes for foreign keys and frequent searches.
CREATE INDEX USER_ACCOUNT_IX_CUSTOMER ON USER_ACCOUNT (CustomerID);
CREATE INDEX USER_ACCOUNT_IX_ROLE ON USER_ACCOUNT (RoleID);
CREATE INDEX CUSTOMER_ADDRESS_IX_CUST ON CUSTOMER_ADDRESS (CustomerID);
CREATE INDEX SUPPLIER_ADDRESS_IX_SUPP ON SUPPLIER_ADDRESS (SupplierID);
CREATE INDEX PRODUCT_IX_CATEGORY ON PRODUCT (CategoryID);
CREATE INDEX PRODUCT_IX_CONDITION ON PRODUCT (ConditionID);
CREATE INDEX PRODUCT_VARIANT_IX_SIZE ON PRODUCT_VARIANT (SizeID);
CREATE INDEX SALES_TRANSACTION_IX_USER ON SALES_TRANSACTION (UserID);
CREATE INDEX SALES_TRANSACTION_IX_CUST ON SALES_TRANSACTION (CustomerID);
CREATE INDEX SALES_ITEM_IX_VARIANT ON SALES_ITEM (VariantID);
CREATE INDEX PAYMENT_IX_SALE ON PAYMENT (SaleID);
CREATE INDEX PAYMENT_IX_METHOD ON PAYMENT (MethodID);
CREATE INDEX PURCHASE_ORDER_IX_SUPP ON PURCHASE_ORDER (SupplierID);
CREATE INDEX PURCHASE_ORDER_IX_USER ON PURCHASE_ORDER (UserID);
CREATE INDEX PURCHASE_ORDER_ITEM_IX_VAR ON PURCHASE_ORDER_ITEM (VariantID);

